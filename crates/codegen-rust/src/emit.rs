//! Emission scaffolding (issue 015): deterministic Rust source with the
//! ADR-013 readability contract — no timestamps, stable ordering, fixed
//! wrapping — so regeneration diffs only when the grammar changed.

use std::fmt::Write as _;

use crate::table::CompactTable;

/// Incremental source builder with deterministic layout rules.
#[derive(Debug, Clone)]
pub struct Emitter {
    out: String,
}

/// Cells per line when emitting flat arrays (stable wrapping).
const CELLS_PER_LINE: usize = 12;

impl Emitter {
    /// Start a file with the generated-code banner (deterministic: no
    /// timestamps or environment data).
    #[must_use]
    pub fn new(grammar_name: &str, grammar_version: &str) -> Self {
        let mut out = String::new();
        out.push_str("// Generated by syntact — DO NOT EDIT.\n");
        out.push_str("// Source grammar: ");
        out.push_str(grammar_name);
        out.push_str(" v");
        out.push_str(grammar_version);
        out.push('\n');
        out.push_str("// Regeneration is diff-stable (ADR-013): identical\n");
        out.push_str("// grammars produce byte-identical files.\n");
        Self { out }
    }

    /// Emit a `#[rustfmt::skip]` static array for a [`CompactTable`]:
    /// the flat cells first, then the base offsets.
    pub fn static_table(&mut self, name: &str, table: &CompactTable) {
        self.out.push_str("#[rustfmt::skip]\n");
        self.out.push_str("pub static ");
        self.out.push_str(name);
        self.out.push_str(": [u16; ");
        self.out.push_str(&table.cells.len().to_string());
        self.out.push_str("] = [\n");
        self.emit_u16_slice(&table.cells);
        self.out.push_str("];\n\n");
        let bases_name = format!("{name}_BASES");
        self.out.push_str("#[rustfmt::skip]\n");
        self.out.push_str("pub static ");
        self.out.push_str(&bases_name);
        self.out.push_str(": [u32; ");
        self.out.push_str(&table.bases.len().to_string());
        self.out.push_str("] = [\n");
        self.out.push_str("    ");
        for (idx, base) in table.bases.iter().enumerate() {
            if idx > 0 {
                self.out.push(' ');
            }
            self.out.push_str(&base.to_string());
            self.out.push(',');
        }
        self.out.push_str("\n];\n\n");
    }

    /// Emit a named `u16` constant.
    pub fn const_u16(&mut self, name: &str, value: u16) {
        self.out.push_str("pub const ");
        self.out.push_str(name);
        self.out.push_str(": u16 = ");
        self.out.push_str(&value.to_string());
        self.out.push_str(";\n");
    }

    /// Emit a named `u32` constant.
    pub fn const_u32(&mut self, name: &str, value: u32) {
        self.out.push_str("pub const ");
        self.out.push_str(name);
        self.out.push_str(": u32 = ");
        self.out.push_str(&value.to_string());
        self.out.push_str(";\n");
    }

    /// Emit an inline O(1) lookup helper for a table (row, col → cell).
    pub fn lookup_fn(&mut self, fn_name: &str, table_name: &str) {
        let bases = format!("{table_name}_BASES");
        let _ = writeln!(
            self.out,
            "/// O(1) cell lookup: `{table_name}[{bases}[row] + col]`."
        );
        let _ = writeln!(
            self.out,
            "pub fn {fn_name}(row: usize, col: usize) -> Option<u16> {{"
        );
        let _ = writeln!(
            self.out,
            "    let cell = {table_name}.get({bases}.get(row)? as usize + col)?;"
        );
        self.out.push_str("    Some(cell)\n}\n\n");
    }

    /// Finish and hand over the source text.
    #[must_use]
    pub fn finish(self) -> String {
        self.out
    }

    fn emit_u16_slice(&mut self, cells: &[u16]) {
        for chunk in cells.chunks(CELLS_PER_LINE) {
            self.out.push_str("    ");
            for (idx, cell) in chunk.iter().enumerate() {
                if idx > 0 {
                    self.out.push(' ');
                }
                let _ = write!(self.out, "{cell},");
            }
            self.out.push('\n');
        }
    }
}

#[cfg(test)]
mod tests {
    use crate::Emitter;
    use crate::table::CompactTable;

    #[test]
    fn emission_is_byte_identical_across_runs() {
        let rows = vec![vec![Some(1), None, Some(2)], vec![None, Some(3), None]];
        let build = || {
            let table = CompactTable::from_rows(&rows, 0xFFFF);
            let mut e = Emitter::new("json", "1.0.0");
            e.static_table("ACTIONS", &table);
            e.const_u16("EMPTY", 0xFFFF);
            e.lookup_fn("action", "ACTIONS");
            e.finish()
        };
        let a = build();
        let b = build();
        assert_eq!(a, b, "regeneration is diff-stable");
    }

    #[test]
    fn emission_shape_has_banner_tables_and_lookup() {
        let rows = vec![vec![Some(9), None], vec![None, Some(4)]];
        let table = CompactTable::from_rows(&rows, 0xFFFF);
        let mut e = Emitter::new("json", "1.0.0");
        e.static_table("ACTIONS", &table);
        e.const_u16("KIND_OBJECT", 0);
        e.lookup_fn("action", "ACTIONS");
        let src = e.finish();
        assert!(src.starts_with("// Generated by syntact — DO NOT EDIT.\n"));
        assert!(src.contains("// Source grammar: json v1.0.0\n"));
        assert!(
            src.contains(&format!(
                "#[rustfmt::skip]\npub static ACTIONS: [u16; {}]",
                table.cells.len()
            )),
            "flat cells emitted"
        );
        assert!(
            src.contains("pub static ACTIONS_BASES: [u32; 2]"),
            "base offsets emitted"
        );
        assert!(src.contains("pub const KIND_OBJECT: u16 = 0;\n"));
        assert!(
            src.contains("pub fn action(row: usize, col: usize) -> Option<u16>"),
            "lookup fn emitted"
        );
        // Stable wrapping: 12 cells per line in flat arrays.
        assert!(src.contains("    9,"), "first cell line");
        // No timestamps or environment data leak into the output.
        assert!(!src.contains("generated at"), "no timestamps");
        assert!(!src.contains("2026"), "no dates");
    }

    #[test]
    fn emitted_lookup_round_trips_through_the_source_shape() {
        // The emitted lookup expression mirrors CompactTable::get: simulate
        // it against the encoded arrays.
        let rows = vec![
            vec![Some(1), None, Some(2)],
            vec![None, Some(3), None],
            vec![Some(4), None, Some(5)],
        ];
        let table = CompactTable::from_rows(&rows, 0xFFFF);
        // The emitted expression: TABLE.get(BASES[row] + col) — same data,
        // same semantics.
        for (row, cells) in rows.iter().enumerate() {
            for (col, expected) in cells.iter().enumerate() {
                let base = table.bases[row] as usize;
                let cell = table.cells.get(base + col).copied();
                let got = cell.filter(|c| *c != table.empty);
                assert_eq!(got, *expected, "emitted shape at ({row}, {col})");
            }
        }
    }
}
